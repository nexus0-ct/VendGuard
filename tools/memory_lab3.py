#!/usr/bin/env python3
"""Extract linked allocations and static frames; never labels them runtime usage."""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re
import subprocess

parser=argparse.ArgumentParser()
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
expected=subprocess.check_output(['python3',str(root/'tools/source_id.py')],text=True).strip()
elf=root/'firmware/build/firmware.elf';binary=elf.read_bytes()
embedded=sorted(set(x.decode() for x in re.findall(rb'vg3-[0-9a-f]{16}',binary)))
if expected not in embedded:raise SystemExit('ELF does not match current source fingerprint')
make=(root/'firmware/Makefile').read_text()
source={Path(s).stem:s for s in re.findall(r'^([\w/]+\.c)\s*\\?$',make,re.M)}
def group(obj):
    if 'libc_nano.a' in obj or 'libnosys.a' in obj:return 'newlib'
    if 'libgcc.a' in obj:return 'compiler support'
    name=Path(obj).stem
    p=source.get(name,'Core/startup')
    return p.split('/')[0]
totals=defaultdict(lambda:{'flash_linked':0,'ram_static':0})
linkmap=(root/'firmware/build/firmware.map').read_text()
active=False; section=''; contributions=[]
rodata_size=0
for line in linkmap.splitlines():
    if line.startswith('Linker script and memory map'):active=True;continue
    if not active:continue
    output_section=re.match(r'^\.rodata\s+0x[0-9a-f]+\s+(0x[0-9a-f]+)',line)
    if output_section:rodata_size=int(output_section[1],16)
    match=re.match(r'^ (\.[\w.$]+)(?:\s+|$)',line)
    if match:section=match[1]
    match=re.search(r'\s+(0x[0-9a-f]+)\s+(0x[0-9a-f]+)\s+(\S+(?:\.o|\)))$',line)
    if not match or not section:continue
    # GNU ld pools strings across input objects; input rows can overlap and
    # show their pre-merge sizes. Attribute the final output .rodata once.
    if section.startswith('.rodata'):continue
    address,size=int(match[1],16),int(match[2],16);obj=match[3]
    if not size:continue
    flash=0x08000000<=address<0x08007000
    ram=0x20000000<=address<0x20003000
    initialized=ram and (section.startswith('.data') or section.startswith('.RamFunc'))
    if flash or ram:
        bucket=totals[group(obj)]
        bucket['flash_linked']+=size if flash or initialized else 0
        bucket['ram_static']+=size if ram else 0
        contributions.append({'section':section,'address':hex(address),'bytes':size,'object':obj})
totals['shared read-only constants']['flash_linked']=rodata_size
frames=[]
for p in (root/'firmware/build').glob('*.su'):
    for line in p.read_text().splitlines():
        fn,n,kind=line.split('\t');frames.append({'function':fn,'bytes':int(n),'kind':kind})
frames.sort(key=lambda x:-x['bytes'])
result={'build':expected,'elf_embedded_ids':embedded,'elf_sha256':hashlib.sha256(binary).hexdigest(),
        'base_head':subprocess.check_output(['git','rev-parse','HEAD'],cwd=root,text=True).strip(),
        'linked_modules':dict(totals),'map_contributions':contributions,'static_frames':frames,
        'stack_reserve':2048,'heap_linker_minimum':512,
        'notes':['Input sections discarded by the linker are excluded.',
                 'All final .rodata is reported once as shared constants; overlapping pre-merge string rows are not summed per object.',
                 'Alignment and linker-generated bytes are not assigned to a source module.',
                 'Initialized RAM and RamFunc also occupy a flash load image.',
                 'A single compiler frame is not a complete stack depth. Newlib static call frames are not in these .su files.',
                 'Runtime stack high-water and heap require actual MCU MEM output.']}
args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'build':expected,'modules':dict(totals),'largest_frame':frames[0]},ensure_ascii=False))
